using System.Globalization;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using HackathonStarter.Agents;
using HackathonStarter.Features.Checks;

namespace HackathonStarter.Features.Exports;

/// <summary>What an exporter receives: a SAVED run (personal data already masked) and the checks it must pass.</summary>
public record RunExportContext(AgentRun Run, IReadOnlyList<string> CheckIds, string AppName);

/// <summary>
/// Turns an agent run into a file: a regression test, a report… Add your own (e.g. a KYC report for a bank)
/// and register it with <c>services.AddSingleton&lt;IRunExporter, MyExporter&gt;()</c>.
/// </summary>
public interface IRunExporter
{
    /// <summary>URL-safe id ("xunit").</summary>
    string Format { get; }
    string Label { get; }
    string FileExtension { get; }
    string ContentType { get; }
    string Export(RunExportContext context);
}

internal static class ExportText
{
    public static string Answer(AgentRun run) =>
        string.Join("\n\n", run.Steps.Where(s => s.Kind == StepKind.Text && !string.IsNullOrWhiteSpace(s.Text))
            .Select(s => s.Agent is null ? s.Text : $"{s.Agent}: {s.Text}"));

    public static List<CheckResult> ObservedChecks(AgentRun run) =>
        run.Steps.LastOrDefault(s => s.Kind == StepKind.Check)?.Checks ?? [];

    /// <summary>"Is RO49… valid?" → "is_ro49_valid" (a C# identifier fragment).</summary>
    public static string Identifier(string text, int max = 48)
    {
        var words = Regex.Split(Services.TextMatch.Normalize(text), "[^a-z0-9]+").Where(w => w.Length > 0);
        var id = string.Join('_', words);
        if (id.Length > max) id = id[..max].TrimEnd('_');
        return id.Length == 0 || char.IsDigit(id[0]) ? "run_" + id : id;
    }

    /// <summary>A C# string literal (JSON escaping is valid C# escaping).</summary>
    public static string Literal(string value) => JsonSerializer.Serialize(value);
}

/// <summary>
/// Portable test case (JSON): the request, the checks the answer must pass, and what was observed when the run
/// was exported. Any test runner can replay it against <c>POST /api/agents/{agent}</c> + <c>POST /api/checks/evaluate</c>.
/// </summary>
public class JsonTestCaseExporter : IRunExporter
{
    public string Format => "json-test";
    public string Label => "Test case (JSON)";
    public string FileExtension => "json";
    public string ContentType => "application/json";

    public string Export(RunExportContext c) => JsonSerializer.Serialize(new
    {
        schema = "hackathon-starter/test-case@1",
        id = c.Run.Id,
        name = ExportText.Identifier(c.Run.Input),
        agent = c.Run.Agent,
        input = c.Run.Input,
        checks = c.CheckIds,
        expect = "all-checks-pass",
        observed = new
        {
            runId = c.Run.Id,
            at = c.Run.CreatedAt,
            source = c.Run.Source.ToString(),
            model = c.Run.Model,
            answer = ExportText.Answer(c.Run),
            checks = ExportText.ObservedChecks(c.Run).Select(r => new { r.CheckId, r.Version, outcome = r.Outcome.ToString(), r.Reason }),
        },
    }, new JsonSerializerOptions(RunStore.Json) { WriteIndented = true });
}

/// <summary>
/// An xUnit test class to commit to a test project. It calls the running app over HTTP (APP_BASE_URL, optional
/// APP_API_KEY): asks the agent the same question and asserts that every listed check passes. A run where an
/// attack succeeded becomes a test that stays red until the weakness is fixed.
/// </summary>
public class XunitTestExporter : IRunExporter
{
    public string Format => "xunit";
    public string Label => "xUnit test (C#)";
    public string FileExtension => "cs";
    public string ContentType => "text/plain";

    public string Export(RunExportContext c)
    {
        var name = ExportText.Identifier(c.Run.Input);
        var className = $"Regression_{ExportText.Identifier(c.Run.Agent, 24)}_{c.Run.Id}";
        var checks = string.Join(", ", c.CheckIds.Select(ExportText.Literal));
        var observed = ExportText.ObservedChecks(c.Run);
        var observedNote = observed.Count == 0
            ? "no checks were recorded on the original run"
            : string.Join(", ", observed.Select(r => $"{r.CheckId}={r.Outcome}"));

        return $$"""
            // Generated by {{c.AppName}} from agent run {{c.Run.Id}} ({{c.Run.CreatedAt.ToString("yyyy-MM-dd HH:mm", CultureInfo.InvariantCulture)}} UTC).
            // Original run: {{observedNote}}. Personal data in the request was masked when the run was saved.
            // Needs: xunit. Run against the app with APP_BASE_URL (default http://localhost:5000) and, if set, APP_API_KEY.
            using System.Net.Http.Json;
            using System.Text.Json;
            using Xunit;

            public class {{className}}
            {
                private const string Agent = {{ExportText.Literal(c.Run.Agent)}};
                private const string Input = {{ExportText.Literal(c.Run.Input)}};
                private static readonly string[] Checks = [{{checks}}];

                [Fact]
                public async Task Replays_{{name}}()
                {
                    using var http = new HttpClient
                    {
                        BaseAddress = new Uri(Environment.GetEnvironmentVariable("APP_BASE_URL") ?? "http://localhost:5000"),
                        Timeout = TimeSpan.FromMinutes(3),
                    };
                    if (Environment.GetEnvironmentVariable("APP_API_KEY") is { Length: > 0 } key) http.DefaultRequestHeaders.Add("X-Api-Key", key);

                    var run = await PostAsync(http, $"/api/agents/{Agent}?stream=false", new { messages = new[] { new { role = "user", content = Input } } });
                    var answer = string.Join("\n\n", run.GetProperty("run").GetProperty("steps").EnumerateArray()
                        .Where(s => s.GetProperty("kind").GetString() == "Text" && s.TryGetProperty("text", out _))
                        .Select(s => s.GetProperty("text").GetString()));
                    if (Checks.Length == 0)
                    {
                        Assert.False(string.IsNullOrWhiteSpace(answer), "The agent gave no answer.");
                        return;
                    }

                    var report = await PostAsync(http, "/api/checks/evaluate", new { text = answer, prompt = Input, checks = Checks });
                    var failed = report.GetProperty("results").EnumerateArray()
                        .Where(r => r.GetProperty("outcome").GetString() == "Fail")
                        .Select(r => $"{r.GetProperty("checkId").GetString()}: {r.GetProperty("reason").GetString()}")
                        .ToList();
                    Assert.True(failed.Count == 0, string.Join("\n", failed));
                }

                private static async Task<JsonElement> PostAsync(HttpClient http, string url, object body)
                {
                    using var response = await http.PostAsJsonAsync(url, body);
                    response.EnsureSuccessStatusCode();
                    return await response.Content.ReadFromJsonAsync<JsonElement>();
                }
            }

            """;
    }
}

/// <summary>Human-readable report of a run: request, answer, actions, approvals, check verdicts.</summary>
public class MarkdownReportExporter : IRunExporter
{
    public string Format => "markdown";
    public string Label => "Report (Markdown)";
    public string FileExtension => "md";
    public string ContentType => "text/markdown";

    public string Export(RunExportContext c)
    {
        var run = c.Run;
        var sb = new StringBuilder();
        sb.AppendLine($"# {run.Input.ReplaceLineEndings(" ")}").AppendLine();
        sb.AppendLine($"- **Agent:** {run.Agent}");
        sb.AppendLine($"- **Run:** {run.Id} · {run.CreatedAt.ToString("yyyy-MM-dd HH:mm", CultureInfo.InvariantCulture)} UTC · {run.Status} · source {run.Source}{(run.Model is null ? "" : $" · {run.Model}")}");
        sb.AppendLine("- **Personal data:** masked when the run was saved ([CNP-1]-style placeholders).").AppendLine();

        sb.AppendLine("## Answer").AppendLine().AppendLine(ExportText.Answer(run) is { Length: > 0 } answer ? answer : "_(no answer)_").AppendLine();

        var actions = run.Steps.Where(s => s.Kind is StepKind.ToolCall or StepKind.Approval).ToList();
        if (actions.Count > 0)
        {
            sb.AppendLine("## Actions").AppendLine();
            foreach (var s in actions)
            {
                if (s.Kind == StepKind.Approval)
                    sb.AppendLine($"- Approval: {s.Summary} → **{s.State}**{(s.DecidedBy is null ? "" : $" by {s.DecidedBy}")}");
                else
                {
                    var result = run.Steps.FirstOrDefault(r => r.Kind == StepKind.ToolResult && r.Id == s.Id);
                    sb.AppendLine($"- `{s.Tool}` {(result?.Error is { } error ? $"failed: {error}" : "ok")}");
                }
            }
            sb.AppendLine();
        }

        var checks = ExportText.ObservedChecks(run);
        if (checks.Count > 0)
        {
            sb.AppendLine("## Checks").AppendLine();
            sb.AppendLine("| Check | Outcome | Reason |").AppendLine("| --- | --- | --- |");
            foreach (var r in checks)
                sb.AppendLine($"| {r.Title} (`{r.CheckId}` v{r.Version}) | {r.Outcome} | {r.Reason.Replace("|", "\\|")} |");
            sb.AppendLine();
            sb.AppendLine($"Fingerprint: `{run.Steps.Last(s => s.Kind == StepKind.Check).Output}`");
        }
        return sb.ToString();
    }
}
