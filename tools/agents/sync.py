#!/usr/bin/env python3
"""Generate Claude Code and OpenCode agent/command files from docs/agents and docs/commands.

docs/agents/<name>.md and docs/commands/<name>.md are the single source; run this after editing them:
    python3 tools/agents/sync.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC_AGENTS, SRC_COMMANDS = ROOT / "docs/agents", ROOT / "docs/commands"
HEADER = "<!-- Generated by tools/agents/sync.py from {src}. Edit the source, then rerun the script. -->\n\n"

BASH = {
    "deny": "  bash: deny\n",
    "allow": "  bash: allow\n",
    "git": '  bash:\n    "*": deny\n    "git diff*": allow\n    "git log*": allow\n    "git status*": allow\n    "git show*": allow\n',
    "build": ('  bash:\n    "*": ask\n    "dotnet build*": allow\n    "dotnet test*": allow\n    "git diff*": allow\n'
              '    "git status*": allow\n    "git log*": allow\n    "git commit*": deny\n    "git push*": deny\n    "gh *": deny\n'),
    "run": ('  bash:\n    "*": ask\n    "dotnet build*": allow\n    "dotnet test*": allow\n    "dotnet run*": allow\n'
            '    "curl -s http://localhost*": allow\n    "git commit*": deny\n    "git push*": deny\n    "gh *": deny\n'),
}


def parse(path: Path) -> tuple[dict[str, str], str]:
    text = path.read_text()
    _, front, body = text.split("---\n", 2)
    meta = {}
    for line in front.strip().splitlines():
        key, _, value = line.partition(":")
        meta[key.strip()] = value.strip()
    return meta, body.strip() + "\n"


def opencode_edit(spec: str) -> str:
    if spec in ("allow", "deny"):
        return f"  edit: {spec}\n"
    globs = [g.strip() for g in spec.split(",") if g.strip()]
    # OpenCode applies the last matching rule, so the catch-all goes first.
    return '  edit:\n    "*": deny\n' + "".join(f'    "{g}": allow\n' for g in globs)


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    print(path.relative_to(ROOT))


def main() -> None:
    protocol = (SRC_AGENTS / "_protocol.md").read_text().strip() + "\n"
    for src in sorted(SRC_AGENTS.glob("[!_]*.md")):
        name, (meta, body) = src.stem, parse(src)
        rel = src.relative_to(ROOT)
        allowed = meta["edit"]
        scope = "" if allowed in ("allow", "deny") else f"\nYou may edit only: {allowed}.\n"
        if allowed == "deny":
            scope = "\nYou may not edit any file.\n"
        full = body + scope + "\n" + protocol

        tools = "" if meta["claude_tools"] == "*" else f"tools: {meta['claude_tools']}\n"
        write(ROOT / f".claude/agents/{name}.md",
              f"---\nname: {name}\ndescription: {meta['description']}\n{tools}model: {meta['model']}\n"
              f"effort: {meta['effort']}\n---\n" + HEADER.format(src=rel) + full)

        write(ROOT / f".opencode/agents/{name}.md",
              f"---\ndescription: {meta['description']}\nmode: {meta['mode']}\npermission:\n"
              + opencode_edit(allowed) + BASH[meta["bash"]] + "---\n" + HEADER.format(src=rel) + full)

    for src in sorted(SRC_COMMANDS.glob("*.md")):
        name, (meta, body) = src.stem, parse(src)
        rel = src.relative_to(ROOT)
        write(ROOT / f".claude/commands/{name}.md",
              f"---\ndescription: {meta['description']}\nargument-hint: [details]\n---\n" + HEADER.format(src=rel) + body)
        agent = f"agent: {meta['agent']}\nsubtask: true\n" if "agent" in meta else ""
        write(ROOT / f".opencode/commands/{name}.md",
              f"---\ndescription: {meta['description']}\n{agent}---\n" + HEADER.format(src=rel) + body)


if __name__ == "__main__":
    main()
